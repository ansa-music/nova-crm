/**
 * Способ оплаты заказа ОС — «Kaspi», «Lavatop» и т.п. (просьба Nurba
 * 23.09.2026). Список один на workspace и правит его ТОЛЬКО Owner
 * («Настройки → Касса»); у способа своя комиссия, которую касса вычитает из
 * суммы: у «Kaspi» 0 %, у «Lavatop» 8 %.
 *
 * В строке стола ОС способ хранится ОТДЕЛЬНО у цены и у апсейла (у них
 * бывают разные способы) — в ячейках `{ключ столбца}__pay` (id способа) и
 * `{ключ столбца}__fee` (комиссия в процентах, СНИМОК на момент выбора).
 * Снимок — чтобы правка процента в настройках не переписывала задним числом
 * уже проданные заказы: деньги по ним считали по старой комиссии.
 */
export interface PaymentMethod {
  id: string;
  label: string;
  /** Комиссия в процентах, 0–100: у «Lavatop» — 8. */
  commissionPct: number;
  /** Цвет чипа (hex). Нет — нейтральный. */
  color?: string;
  /**
   * Способ больше не предлагают при выборе, но заказы с ним по-прежнему
   * показывают его подпись. Удалять способ не нужно — как с никами ОС.
   */
  inactive?: boolean;
}

/** Порог KPI ОС: добил долю заказов в «Готово» не ниже `minPct` — фиксированный оклад. */
export interface OsKpiTier {
  id: string;
  minPct: number;
  amount: number;
}

/**
 * Зарплатная система ОС в «ABS» (просьба Nurba 23.09.2026) — правит только
 * Owner в «Настройки → Касса». Всё за текущий месяц по Алматы.
 */
export interface OsPaySettings {
  /** Процент ОС от каждого апсейла ПОСЛЕ комиссии способа оплаты (по умолчанию 8). */
  upsellPct: number;
  /** Доп. оклад ОС с лучшим KPI («Готово» / все заказы). 0 — нет. */
  kpiTopBonus: number;
  /** Меньше заказов за месяц — в KPI-топ и пороги не попадает (1 заказ = 100 % не считается). */
  kpiMinOrders: number;
  /** Пороги KPI с фиксированным окладом; берётся самый высокий из добитых. */
  kpiTiers: OsKpiTier[];
}
